  document.addEventListener("eco:pronto", function () {
    const { enviar, $, $$ } = EcoApp;
    const form = $("#diag"), msg = $(".form-msg", form);
    let canal = "whatsapp";
    $$("[data-send]", form).forEach((b) => b.addEventListener("click", () => { canal = b.dataset.send; }));
    form.addEventListener("submit", (e) => {
      e.preventDefault();
      const f = new FormData(form), g = (k) => (f.get(k) || "").toString().trim();
      $$(".invalid", form).forEach((el) => el.classList.remove("invalid"));
      const contactoOk = /^[^\s@]+@[^\s@]+\.[^\s@]+$/.test(g("contacto")) || g("contacto").replace(/\D/g, "").length >= 9;
      const erros = [];
      if (g("nome").length < 2) { erros.push("nome"); form.elements.nome.classList.add("invalid"); }
      if (!contactoOk) { erros.push("contacto"); form.elements.contacto.classList.add("invalid"); }
      if (g("tarefa").length < 10) { erros.push("tarefa"); form.elements.tarefa.classList.add("invalid"); }
      if (!form.elements.consentimento.checked) erros.push("consentimento");
      if (erros.length) {
        msg.className = "form-msg err";
        msg.textContent = erros.length === 1 && erros[0] === "consentimento" ? "Confirme que aceita a política de privacidade." : "Indique o nome, um contacto válido e a tarefa que quer automatizar.";
        canal = "whatsapp"; return;
      }
      const texto = "Olá ECOMULTI! Pedido de *diagnóstico básico de automação com IA*.\n\n" +
        "Nome: " + g("nome") + "\nContacto: " + g("contacto") + "\n" + (g("empresa") ? "Empresa: " + g("empresa") + "\n" : "") + (g("sector") ? "Sector: " + g("sector") + "\n" : "") +
        "Equipa: " + g("equipa") + "\nProcesso a automatizar: " + g("area") + "\n" + (g("ferramentas") ? "Ferramentas actuais: " + g("ferramentas") + "\n" : "") +
        "\nTarefa repetitiva principal:\n" + g("tarefa");
      enviar(canal, texto, "Diagnóstico de automação com IA - " + g("nome"));
      msg.className = "form-msg ok";
      msg.textContent = canal === "email" ? "A abrir o seu e-mail com o diagnóstico preenchido. Só falta carregar em Enviar." : "A abrir o WhatsApp com o diagnóstico preenchido. Só falta carregar em Enviar.";
      canal = "whatsapp";
    });
  });
