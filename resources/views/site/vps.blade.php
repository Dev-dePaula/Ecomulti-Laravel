  document.addEventListener("eco:pronto", function () {
    const { kz, Orcamento, toast, $, $$ } = EcoApp;
    const V = ECOMULTI.vps;
    let ciclo = "mensal";
    try { ciclo = localStorage.getItem("vps_ciclo") || "mensal"; } catch (e) {}
    if (!V.ciclos[ciclo]) ciclo = "mensal";
    const calc = (id, c) => { const p = V.planos[id], k = V.ciclos[c], cheio = p.preco * k.meses, total = Math.round(cheio * (1 - k.desc)); return { cheio, total, mes: total / k.meses }; };
    function render() {
      $("#vpsCiclos").innerHTML = Object.entries(V.ciclos).map(([k, c]) =>
        '<label><input type="radio" name="ciclo" value="' + k + '"' + (k === ciclo ? " checked" : "") + '><span class="seg-box"><strong>' + c.nome + '</strong>' + (c.rotulo ? '<br><em>' + c.rotulo + '</em>' : "") + '</span></label>').join("");
      $("#vpsPlanos").innerHTML = Object.entries(V.planos).map(([id, p]) => {
        const r = calc(id, ciclo), k = V.ciclos[ciclo];
        return '<article class="plan' + (p.destaque ? " featured" : "") + '">' + (p.destaque ? '<span class="ribbon">Mais vendido</span>' : "") +
          '<span class="tier">' + p.cpu + ' · ' + p.ram + '</span><h3>' + p.nome + '</h3>' +
          '<p class="desc">' + p.disco + ' · ' + p.banda + ' de tráfego</p>' +
          '<div class="price"><strong>' + kz(r.mes) + '</strong><span>/mês</span></div>' +
          '<div class="billing">' + (k.desc ? 'em vez de ' + kz(p.preco) + '/mês · ' : "") + 'Total do ciclo: ' + kz(r.total) + '</div>' +
          '<ul>' + p.itens.map((i) => '<li><svg class="icon"><use href="#i-tick"/></svg> ' + i + '</li>').join("") + '</ul>' +
          '<button class="btn ' + (p.destaque ? "btn-primary" : "btn-outline") + '" type="button" data-vps="' + id + '">Adicionar ao orçamento</button></article>';
      }).join("");
    }
    document.addEventListener("change", (e) => {
      if (e.target.name !== "ciclo") return;
      ciclo = e.target.value; try { localStorage.setItem("vps_ciclo", ciclo); } catch (x) {}
      render();
    });
    document.addEventListener("click", (e) => {
      const b = e.target.closest("[data-vps]"); if (!b) return;
      const id = b.dataset.vps, p = V.planos[id], k = V.ciclos[ciclo], r = calc(id, ciclo);
      Orcamento.adicionar({
        servico: "vps", servicoLabel: "Servidor VPS", icon: "server", plano: p.nome,
        detalhes: [p.cpu + " · " + p.ram + " · " + p.disco, k.meses + (k.meses === 1 ? " mês" : " meses") + " (" + k.nome.toLowerCase() + ") × " + kz(p.preco) + "/mês", k.desc ? "Desconto de " + Math.round(k.desc * 100) + "% incluído" : null].filter(Boolean),
        total: r.total
      });
      toast(p.nome + " adicionado ao orçamento.", { href: "orcamento-ecomulti.html", text: "Ver orçamento →" });
    });
    render();
  });
